"""Render docs/eval/RESULTS.md from docs/eval/results/*.json (after fixes) and docs/eval/results/before/*.json.

Usage: uv run python scripts/eval_report.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "docs" / "eval"
RES, BEFORE = ROOT / "results", ROOT / "results" / "before"

# (section, row label, result file stem, aggregate key)
ROWS = [
    ("Speech recognition (Whisper small, int8, CPU)", "LibriSpeech test-clean, 80 utt. — WER", "wer_librispeech_clean", "wer"),
    ("", "LibriSpeech test-other, 66 utt. — WER", "wer_librispeech_other", "wer"),
    ("", "12 formats × 3 utt. — WER", "wer_formats", "wer"),
    ("", "Ambient noise 20 dB SNR, 30 utt. — WER", "wer_noise_snr20", "wer"),
    ("", "Ambient noise 10 dB SNR — WER", "wer_noise_snr10", "wer"),
    ("", "Ambient noise 5 dB SNR — WER", "wer_noise_snr5", "wer"),
    ("", "Ambient noise 0 dB SNR — WER", "wer_noise_snr0", "wer"),
    ("Multilingual (FLEURS test, 25 utt. each)", "English — WER", "wer_fleurs_en_us", "wer"),
    ("", "Spanish — WER", "wer_fleurs_es_419", "wer"),
    ("", "French — WER", "wer_fleurs_fr_fr", "wer"),
    ("", "German — WER", "wer_fleurs_de_de", "wer"),
    ("", "Arabic — WER", "wer_fleurs_ar_eg", "wer"),
    ("", "Hindi — WER", "wer_fleurs_hi_in", "wer"),
    ("", "Telugu — WER", "wer_fleurs_te_in", "wer"),
    ("", "Mandarin — CER", "cer_fleurs_cmn_hans_cn", "cer"),
    ("Speaker diarization (ECAPA, no overlap detection)", "AMI test, 4 meetings — DER, no collar", "der_ami_collar0", "der"),
    ("", "AMI test, 4 meetings — DER, 0.25 s collar", "der_ami_collar025", "der"),
    ("", "Simulated LibriSpeech dialogues, 12 — DER, 0.25 s collar", "der_simulated", "der"),
    ("Sound events (PANNs CNN14, AudioSet labels)", "ESC-50, 200 clips — clip recall (strict label)", "events_esc50_strict", "recall"),
    ("", "ESC-50 — top-1 accuracy (strict label)", "events_esc50_strict", "top1_accuracy"),
    ("", "ESC-50 — clip recall (lenient labels)", "events_esc50_lenient", "recall"),
    ("", "ESC-50 — top-1 accuracy (lenient labels)", "events_esc50_lenient", "top1_accuracy"),
    ("Quality diagnosis (90 files: 8 injected defects + clean)", "Exact issue set per file", "quality_injected", "exact_match"),
]


def _load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _pct(x):
    return "—" if x is None else f"{100 * x:.1f}%"


def _rerun(stem):
    a, b = RES / f"{stem}.json", BEFORE / f"{stem}.json"
    return a.exists() and b.exists() and a.stat().st_mtime > b.stat().st_mtime + 60


def main():
    out = ["# Evaluation results", "",
           "Generated by `scripts/eval_report.py` from `docs/eval/results/*.json`. *Before* = first run on "
           "2026-10-19 (`results/before/`); *After* = after the fixes in "
           "[the fix plan](../superpowers/plans/2026-10-19-eval-fixes.md). Rows whose code path the fixes did not "
           "touch were not re-run and show the After value only. Datasets, setup and caveats: "
           "[../evaluation.md](../evaluation.md)."]
    section = None
    for sec, label, stem, key in ROWS:
        if sec and sec != section:
            section = sec
            out += ["", f"### {sec}", "", "| Evaluation | Before | After | Language detected |", "|---|---|---|---|"]
        after, before = _load(RES / f"{stem}.json"), _load(BEFORE / f"{stem}.json")
        a = after["aggregate"].get(key) if after else None
        b = before["aggregate"].get(key) if before and _rerun(stem) else None
        lang = after["aggregate"].get("language_accuracy") if after else None
        out.append(f"| {label} | {_pct(b) if b is not None else ''} | {_pct(a)} | {_pct(lang) if lang is not None else ''} |")
    q, qb = _load(RES / "quality_injected.json"), _load(BEFORE / "quality_injected.json")
    if q:
        out += ["", "#### Quality diagnosis per issue (precision / recall)", "", "| Issue | Before | After |",
                "|---|---|---|"]
        for code, v in q["per_issue"].items():
            w = (qb or {}).get("per_issue", {}).get(code, {})
            out.append(f"| {code} | {_pct(w.get('precision'))} / {_pct(w.get('recall'))} | "
                       f"{_pct(v['precision'])} / {_pct(v['recall'])} |")
    bench = _load(RES / "benchmark_long_10min.json")
    if bench:
        out += ["", f"### Speed (10.3 min LibriSpeech concatenation, CPU, 1 run, peak RSS "
                    f"{bench['peak_rss_mb'] / 1024:.1f} GB)", "", "| Stage | Seconds | Real-time factor |", "|---|---|---|"]
        out += [f"| {s['stage']} | {s['mean_seconds']:.1f} | {s['rtf']:.3f} |" for s in bench["stages"]]
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {ROOT / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
